/// <reference types="node" />
/**
 * The public pages must carry every legal section and FAQ answer the app shows, use the app's
 * colors, and keep the consent and deletion scripts exactly as written.
 */
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';

import { Colors } from '@/constants/theme';
import { LEGAL_DOCUMENTS } from '@/features/legal/texts';

import {
  behaviourScripts,
  buildSite,
  diffWithDir,
  FORM_PAGES,
  optionsFromEnv,
  readTheme,
  ROOT,
  strictProblems,
  verifySite,
  writeSite,
} from '../site';

const PROD = 'https://abcdefghijklmnopqrst.supabase.co/functions/v1';
const options = optionsFromEnv(
  { WEB_FUNCTIONS_URL: PROD, WEB_BASE_URL: 'https://studyflow.app', EXPO_PUBLIC_SUPPORT_EMAIL: 'destek@studyflow.app' },
  new Date('2027-03-01T10:00:00Z'),
);
const files = buildSite(options);
const html = (file: string) => files.get(file) as string;

describe('public web pages', () => {
  it('have every legal section, FAQ item and form page', () => {
    expect(verifySite(files)).toEqual([]);
  });

  it('use the colors from src/constants/theme.ts', () => {
    const tokens = readTheme();
    for (const mode of ['light', 'dark'] as const) {
      for (const [key, value] of Object.entries(Colors[mode])) {
        expect(tokens[mode][key]).toBe(value.toUpperCase());
      }
    }
    const css = html('assets/site.css');
    expect(css).toContain(`--exam: ${Colors.light.exam.toUpperCase()};`);
    expect(css).toContain(`--ink-soft: ${Colors.dark.inkSoft.toUpperCase()};`);
  });

  it('notice a legal section that went missing', () => {
    const broken = new Map(files);
    const section = LEGAL_DOCUMENTS.gizlilik.sections[1];
    const page = html('gizlilik/index.html').replace(`<h2>${section.heading}</h2>`, '');
    broken.set('gizlilik/index.html', page);
    expect(verifySite(broken)).toEqual(
      expect.arrayContaining([expect.stringContaining(`missing section heading: "${section.heading}"`)]),
    );
    broken.delete('kosullar/index.html');
    expect(verifySite(broken)).toEqual(expect.arrayContaining(['kosullar/index.html: page missing']));
  });

  it('mark drafts and placeholders while the texts await legal review', () => {
    const page = html('kosullar/index.html');
    expect(page).toContain('class="draft"');
    expect(page).toContain('<meta name="robots" content="noindex">');
    expect(page).toContain('<mark class="placeholder">[Şirket unvanı]</mark>');
  });

  it('keep the consent and deletion scripts unchanged and fill in their config', () => {
    for (const page of FORM_PAGES) {
      const source = fs.readFileSync(path.join(ROOT, page.source), 'utf8');
      const built = html(`${page.route}/index.html`);
      expect(behaviourScripts(built)).toEqual(behaviourScripts(source));
      expect(built).toContain(`functionsUrl: '${PROD}'`);
      expect(built).toContain("privacyUrl: '../aydinlatma-metni/'");
      const csp = /http-equiv="Content-Security-Policy" content="([^"]+)"/.exec(built)?.[1] ?? '';
      expect(csp).toContain('connect-src https://abcdefghijklmnopqrst.supabase.co;');
      expect(csp).not.toMatch(/127\.0\.0\.1|localhost/);
      expect(built).not.toContain('fonts.googleapis.com');
    }
    expect(html('veli-onayi/index.html')).toContain("supportEmail: 'destek@studyflow.app'");
  });

  it('build staging copies of the forms when a staging URL is given', () => {
    const staging = buildSite({ ...options, stagingFunctionsUrl: 'https://zyxwvutsrqponmlkjihg.supabase.co/functions/v1' });
    const page = staging.get('staging/veli-onayi/index.html') as string;
    expect(page).toContain("functionsUrl: 'https://zyxwvutsrqponmlkjihg.supabase.co/functions/v1'");
    expect(page).toContain('href="../../assets/site.css"');
    expect(verifySite(staging)).toEqual([]);
  });

  it('report a build folder that is out of date', () => {
    const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'studyflow-web-'));
    try {
      writeSite(files, dir);
      expect(diffWithDir(files, dir)).toEqual([]);
      fs.appendFileSync(path.join(dir, 'gizlilik', 'index.html'), '<!-- edited -->');
      fs.rmSync(path.join(dir, 'destek', 'index.html'));
      fs.writeFileSync(path.join(dir, 'old.html'), 'old');
      expect(diffWithDir(files, dir)).toEqual(
        expect.arrayContaining(['out of date: gizlilik/index.html', 'missing: destek/index.html', 'not generated by the build: old.html']),
      );
    } finally {
      fs.rmSync(dir, { recursive: true, force: true });
    }
  });

  it('refuse to deploy placeholder or local URLs', () => {
    expect(strictProblems(options)).toEqual([]);
    expect(strictProblems({ ...options, functionsUrl: null })).toHaveLength(1);
    expect(strictProblems({ ...options, functionsUrl: 'http://127.0.0.1:54321/functions/v1' }).join(' ')).toMatch(/https/);
  });
});
